"""Render a ``ferrum.conf`` (``KEY=value``) profile for the intended run mode.

Only settings present in Ferrum Edge's public settings inventory
(``src/config/public_env_inventory.rs`` at the reference commit) are emitted.
Secrets are never written: secret-bearing settings appear as comments that tell
the operator to export the matching ``*_FILE`` variable in the environment
(Ferrum resolves ``_FILE`` suffixes from the environment only, never from
``ferrum.conf``). Values the tool cannot know are left as ``# REQUIRED`` comments
so the file stays valid until the operator fills them in.
"""

from __future__ import annotations

from . import FERRUM_EDGE_REFERENCE_COMMIT, __version__
from .model import SettingsHints

RUN_MODES = ("file", "database", "cp", "dp")

#: Subset of Ferrum's public settings inventory that this tool may mention.
KNOWN_SETTINGS = frozenset({
    "FERRUM_MODE", "FERRUM_FILE_CONFIG_PATH", "FERRUM_LOG_LEVEL", "FERRUM_NAMESPACE",
    "FERRUM_PROXY_HTTP_PORT", "FERRUM_PROXY_HTTPS_PORT", "FERRUM_PROXY_BIND_ADDRESS",
    "FERRUM_ADMIN_BIND_ADDRESS", "FERRUM_ADMIN_HTTP_PORT", "FERRUM_ADMIN_JWT_SECRET",
    "FERRUM_FRONTEND_TLS_CERT_PATH", "FERRUM_FRONTEND_TLS_KEY_PATH",
    "FERRUM_FRONTEND_TLS_CLIENT_CA_BUNDLE_PATH", "FERRUM_MAX_REQUEST_BODY_SIZE_BYTES",
    "FERRUM_TRUSTED_PROXIES", "FERRUM_REAL_IP_HEADER", "FERRUM_BASIC_AUTH_HMAC_SECRET",
    "FERRUM_DB_TYPE", "FERRUM_DB_URL", "FERRUM_CP_GRPC_LISTEN_ADDR", "FERRUM_CP_DP_GRPC_JWT_SECRET",
    "FERRUM_DP_CP_GRPC_URLS", "FERRUM_ENABLE_HTTP3", "FERRUM_FRONTEND_PROXY_PROTOCOL_HTTP",
    "FERRUM_FRONTEND_PROXY_PROTOCOL_HTTPS", "FERRUM_FRONTEND_PROXY_PROTOCOL_TRUSTED_CIDRS",
    "FERRUM_K8S_CONTROLLER_ENABLED", "FERRUM_K8S_WATCH_ISTIO_CRDS",
})


class _Lines:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def comment(self, text: str) -> None:
        self.lines.append(f"# {text}" if text else "#")

    def put(self, key: str, value: object, note: str | None = None) -> None:
        assert key in KNOWN_SETTINGS, key
        if note:
            self.comment(note)
        self.lines.append(f"{key}={value}")

    def suggest(self, key: str, value: object, note: str) -> None:
        assert key in KNOWN_SETTINGS, key
        self.comment(note)
        self.lines.append(f"# {key}={value}")

    def blank(self) -> None:
        self.lines.append("")


def render(run_mode: str, platform: str, settings: SettingsHints, tls_only: bool, basic_auth_used: bool,
           resources_name: str) -> str:
    if run_mode not in RUN_MODES:
        raise ValueError(run_mode)
    out = _Lines()
    out.comment(f"Generated by ferrum-migration {__version__} from {platform} input for FERRUM_MODE={run_mode}.")
    out.comment(f"Settings names verified against Ferrum Edge {FERRUM_EDGE_REFERENCE_COMMIT[:12]}.")
    out.comment("This file contains no secrets. Export secret settings as *_FILE variables in the process")
    out.comment("environment (Ferrum does not resolve *_FILE suffixes from ferrum.conf). Review before use.")
    out.blank()
    out.put("FERRUM_MODE", run_mode)
    out.put("FERRUM_LOG_LEVEL", "info")
    out.put("FERRUM_ADMIN_BIND_ADDRESS", "127.0.0.1", "Keep the admin API on loopback; see Ferrum docs before exposing it.")
    if run_mode == "file":
        out.suggest("FERRUM_FILE_CONFIG_PATH", resources_name,
                    f"`ferrum-edge run` discovers ./{resources_name} automatically; set an absolute path otherwise.")
    out.blank()

    if run_mode != "cp":
        out.comment("Listeners")
        if tls_only:
            out.put("FERRUM_PROXY_HTTP_PORT", 0, "Source routes require HTTPS: the plaintext listener is disabled.")
        elif settings.main_http_port:
            out.put("FERRUM_PROXY_HTTP_PORT", settings.main_http_port,
                    "Plaintext port from the source (ports below 1024 need CAP_NET_BIND_SERVICE).")
        if settings.main_https_port:
            out.put("FERRUM_PROXY_HTTPS_PORT", settings.main_https_port, "TLS port from the source.")
        if settings.bind_address:
            out.put("FERRUM_PROXY_BIND_ADDRESS", settings.bind_address,
                    "The source only listened on this address; keep Ferrum on it too.")
        needs_cert = tls_only or settings.frontend_tls_expected or bool(settings.main_https_port)
        pairs = sorted(set(settings.frontend_cert_pairs))
        if needs_cert:
            if len(pairs) == 1:
                out.put("FERRUM_FRONTEND_TLS_CERT_PATH", pairs[0][0], "Certificate path referenced by the source.")
                out.put("FERRUM_FRONTEND_TLS_KEY_PATH", pairs[0][1], "Private key path referenced by the source "
                        "(the tool never reads key files).")
            else:
                if len(pairs) > 1:
                    out.comment(f"The source used {len(pairs)} certificates; Ferrum file mode serves one default "
                                "frontend certificate. Choose one (or a SAN certificate covering all hosts).")
                out.comment("REQUIRED for HTTPS: write the certificate and key to files and set:")
                out.lines.append("# FERRUM_FRONTEND_TLS_CERT_PATH=/etc/ferrum/tls/fullchain.pem")
                out.lines.append("# FERRUM_FRONTEND_TLS_KEY_PATH=/etc/ferrum/tls/privkey.pem")
        cas = sorted(set(settings.client_ca_paths))
        if len(cas) == 1 and not settings.client_ca_scope_conflict:
            out.put("FERRUM_FRONTEND_TLS_CLIENT_CA_BUNDLE_PATH", cas[0],
                    "Every migrated route that required client certificates (mTLS) used this one CA bundle; Ferrum "
                    "applies it to the whole HTTPS listener.")
        elif cas or settings.client_ca_scope_conflict:
            # Never suggest merging bundles: that would let clients trusted by one source scope reach another.
            out.comment("REVIEW REQUIRED (frontend-client-ca-scope): the source required client certificates from")
            out.comment("several CA bundles on separate servers/listeners. One shared Ferrum listener cannot keep")
            out.comment("those trust scopes apart, so no client CA bundle is configured here and the affected routes")
            out.comment("were refused. Do NOT concatenate the bundles. Use a separately configured Ferrum frontend")
            out.comment("per trust boundary, each with its own FERRUM_FRONTEND_TLS_CLIENT_CA_BUNDLE_PATH, and review")
            out.comment("and validate each one. See migration-report.md.")
        if settings.max_request_body_bytes:
            out.put("FERRUM_MAX_REQUEST_BODY_SIZE_BYTES", settings.max_request_body_bytes,
                    "Largest request body any source route accepted; smaller per-route limits use request_size_limiting.")
        if settings.http3:
            out.suggest("FERRUM_ENABLE_HTTP3", "true", "The source enabled HTTP/3 (QUIC).")
        if settings.trusted_proxies:
            out.suggest("FERRUM_TRUSTED_PROXIES", ",".join(settings.trusted_proxies),
                        "SUGGESTED (verify list syntax in Ferrum docs/client_ip_resolution.md): the source trusted "
                        "these proxies for client-IP resolution.")
        if settings.real_ip_header:
            out.suggest("FERRUM_REAL_IP_HEADER", settings.real_ip_header,
                        "SUGGESTED: the source read the client IP from this header.")
        if settings.proxy_protocol:
            out.suggest("FERRUM_FRONTEND_PROXY_PROTOCOL_HTTP", "true",
                        "SUGGESTED: the source accepted PROXY protocol; also set the trusted CIDRs below.")
            out.lines.append("# FERRUM_FRONTEND_PROXY_PROTOCOL_TRUSTED_CIDRS=10.0.0.0/8")
        out.blank()

    if basic_auth_used and run_mode != "cp":
        out.comment("REQUIRED by basic_auth: a unique random secret of at least 32 bytes, exported as")
        out.comment("FERRUM_BASIC_AUTH_HMAC_SECRET_FILE=/run/secrets/ferrum_basic_auth_hmac in the environment.")
        out.blank()

    if run_mode in ("database", "cp"):
        out.comment("Database")
        out.put("FERRUM_DB_TYPE", "sqlite", "Change to postgres, mysql or mongodb as needed.")
        out.comment("REQUIRED: export FERRUM_DB_URL (or FERRUM_DB_URL_FILE when it embeds credentials), e.g.")
        out.lines.append("# FERRUM_DB_URL=sqlite://ferrum.db?mode=rwc")
        out.comment("REQUIRED: export FERRUM_ADMIN_JWT_SECRET_FILE (secret of at least 32 characters).")
        out.blank()
    if run_mode == "cp":
        out.put("FERRUM_CP_GRPC_LISTEN_ADDR", "127.0.0.1:50051", "Loopback by default; use TLS before binding wider.")
        out.comment("REQUIRED: export FERRUM_CP_DP_GRPC_JWT_SECRET_FILE (secret of at least 32 characters).")
        out.blank()
    if run_mode == "dp":
        out.comment("REQUIRED: point the data plane at its control plane(s), e.g.")
        out.lines.append("# FERRUM_DP_CP_GRPC_URLS=https://cp.example.internal:50051")
        out.comment("REQUIRED: export FERRUM_ADMIN_JWT_SECRET_FILE and FERRUM_CP_DP_GRPC_JWT_SECRET_FILE.")
        out.comment("Resources are loaded into the control plane, not into the data plane.")
        out.blank()
    if platform == "istio":
        out.comment("This profile serves an ingress projection of Gateway-bound routes only (no mesh, no workload")
        out.comment("mTLS). Ferrum documents separate Istio CRD support (FERRUM_K8S_CONTROLLER_ENABLED,")
        out.comment("FERRUM_K8S_WATCH_ISTIO_CRDS; see Ferrum docs/mesh.md); ferrum-migration does not exercise it.")
    return "\n".join(out.lines).rstrip("\n") + "\n"


def next_steps(run_mode: str, resources_name: str, tls_only: bool, basic_auth_used: bool,
               secrets_emitted: int) -> list[str]:
    steps = ["Read every error and warning in this report; errors mark refused or fail-closed items."]
    if run_mode == "file":
        steps.append(f"Validate offline: `ferrum-edge validate --settings ferrum.conf --spec {resources_name}`.")
        steps.append(f"Try it: `ferrum-edge run --settings ferrum.conf --spec {resources_name}`.")
    else:
        steps.append(f"Validate the resources in file mode first: `ferrum-edge validate -m file -c {resources_name}`.")
        steps.append("Import them through Ferrum's Admin API yourself. First convert them to JSON and drop the "
                     "file-mode-only top-level `resource_counts` key, which the Admin API does not accept. Then "
                     "choose: `POST /batch` is an additive, all-or-nothing import next to the existing configuration "
                     "(it fails as a whole on conflicts and has a 1 MiB request limit, so split large imports). "
                     "`POST /restore?confirm=true` REPLACES the namespace's entire configuration, so take "
                     "`GET /backup` first. See Ferrum docs/admin_batch_api.md and docs/admin_backup_restore.md.")
        steps.append("This tool performs no network I/O, never connects to a live database, and has not "
                     "runtime-tested either import path.")
    if tls_only:
        steps.append("Provide the frontend certificate and key paths in ferrum.conf (HTTPS only).")
    if basic_auth_used:
        steps.append("Export FERRUM_BASIC_AUTH_HMAC_SECRET_FILE and create Basic-auth credentials in Ferrum's "
                     "hmac_sha256 format; source password hashes cannot be converted.")
    if secrets_emitted:
        steps.append(f"{resources_name} contains {secrets_emitted} plaintext credential(s): keep it private "
                     "(mode 0600) and never commit it.")
    return steps
