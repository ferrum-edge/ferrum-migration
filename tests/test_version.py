"""The package version has one source (``ferrum_migration.__version__``) and every surface reports it."""

import contextlib
import importlib.metadata
import io
import json
import os
import re
import tempfile
import tomllib
import unittest

from helpers import ROOT, fixture_path

import ferrum_migration
from ferrum_migration import FERRUM_EDGE_REFERENCE_COMMIT, __version__
from ferrum_migration.cli import main

STRICT_VERSION = re.compile(r"^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$")


def run_cli(*args):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            code = main(list(args))
        except SystemExit as exc:  # argparse's --version exits
            code = exc.code
    return code, out.getvalue(), err.getvalue()


class VersionSourceTest(unittest.TestCase):
    def test_version_is_strict_semver(self):
        self.assertRegex(__version__, STRICT_VERSION)

    def test_pyproject_reads_the_package_attribute(self):
        with open(os.path.join(ROOT, "pyproject.toml"), "rb") as handle:
            pyproject = tomllib.load(handle)
        project = pyproject["project"]
        self.assertNotIn("version", project, "pyproject.toml must not hard-code a version")
        self.assertIn("version", project["dynamic"])
        self.assertEqual(pyproject["tool"]["setuptools"]["dynamic"]["version"],
                         {"attr": "ferrum_migration.__version__"})

    def test_package_attribute_is_the_only_version_literal(self):
        init = os.path.join(ROOT, "src", "ferrum_migration", "__init__.py")
        with open(init, encoding="utf-8") as handle:
            assignments = re.findall(r"^__version__ = \"([^\"]+)\"$", handle.read(), re.MULTILINE)
        self.assertEqual(assignments, [__version__])
        self.assertEqual(ferrum_migration.__version__, __version__)

    def test_installed_metadata_matches(self):
        # CI installs the checkout (editable) before running the tests; a bare source tree has no metadata.
        try:
            installed = importlib.metadata.version("ferrum-migration")
        except importlib.metadata.PackageNotFoundError:
            self.skipTest("ferrum-migration is not installed")
        self.assertEqual(installed, __version__)


class VersionSurfacesTest(unittest.TestCase):
    def test_cli_version_flag(self):
        code, out, _err = run_cli("--version")
        self.assertEqual(code, 0)
        self.assertEqual(out.strip(),
                         f"ferrum-migration {__version__} (Ferrum Edge reference {FERRUM_EDGE_REFERENCE_COMMIT[:12]})")

    def test_reports_and_outputs_record_the_version(self):
        with tempfile.TemporaryDirectory() as temp:
            out = os.path.join(temp, "out")
            code, stdout, stderr = run_cli("convert", fixture_path("nginx", "nginx.conf"), "--from", "nginx",
                                           "--out", out)
            self.assertEqual(code, 0, stderr + stdout)
            self.assertIn(f"ferrum-migration {__version__}:", stdout)

            def read(name):
                with open(os.path.join(out, name), encoding="utf-8") as handle:
                    return handle.read()

            report = json.loads(read("migration-report.json"))
            self.assertEqual(report["tool_version"], __version__)
            self.assertEqual(report["ferrum_edge_reference_commit"], FERRUM_EDGE_REFERENCE_COMMIT)
            self.assertIn(f"- Tool: ferrum-migration {__version__} ", read("migration-report.md"))
            self.assertIn(f"Generated by ferrum-migration {__version__} ", read("ferrum.conf"))
            self.assertIn(f"generated by ferrum-migration {__version__} ", read("resources.yaml").splitlines()[0])


if __name__ == "__main__":
    unittest.main()
